const formulas: Partial<Record<string, string>> = {
  opv: String.raw`\angle A\hat{O}C \cong \angle B\hat{O}D`,
  sas: String.raw`AB \cong DE,\; \angle B \cong \angle E,\; BC \cong EF`,
  asa: String.raw`\angle A \cong \angle D,\; AB \cong DE,\; \angle B \cong \angle E`,
  sss: String.raw`AB \cong DE,\; BC \cong EF,\; AC \cong DF`,
};

export const codexEntries: CodexEntry[] = skills.map((skill) => ({
  id: skill.codexEntryId,
  skillId: skill.id,
  title: skill.title,
  summary: skill.description,
  statement: skill.formalStatement,
  ...(formulas[skill.id] ? { formula: formulas[skill.id] } : {}),
  unlockedByDefault: skill.prerequisites.length === 0,
  sourceRefs: skill.sourceRefs,
}));

assertValidContent({ skills, regions, encounters, codexEntries, assetManifest });

export function findEncounter(id: string) {
  return encounters.find((encounter) => encounter.id === id);
}

export function findCodexEntry(id: string) {
  return codexEntries.find((entry) => entry.id === id);
}
